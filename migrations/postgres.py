_MIGRATION_LEDGER = """CREATE TABLE schema_migrations (
    version INTEGER PRIMARY KEY, name TEXT NOT NULL, checksum TEXT NOT NULL, applied_at TEXT NOT NULL)"""


def migrate_fresh() -> int:
    """Create a fresh public schema only; never mutate an existing app schema."""
    with postgres_connection() as db:
        db.execute("BEGIN IMMEDIATE")
        row = db.execute("SELECT to_regclass('public.schema_migrations') AS ledger").fetchone()
        ledger_exists = row["ledger"] is not None
        if not ledger_exists:
            existing = db.execute("""SELECT count(*) AS n FROM information_schema.tables
                WHERE table_schema='public' AND table_type='BASE TABLE'""").fetchone()["n"]
            if existing:
                raise RuntimeError("PostgreSQL public schema is not empty; refusing to initialize or adopt existing data.")
            db.execute(_MIGRATION_LEDGER)
            applied = []
        else:
            applied = db.execute("SELECT version,name,checksum FROM schema_migrations ORDER BY version").fetchall()

        versions = [int(record["version"]) for record in applied]
        if versions != list(range(1, len(versions) + 1)):
            raise RuntimeError("PostgreSQL migration history is not contiguous; refusing to continue.")
        known = {revision.version: revision for revision in POSTGRES_MIGRATIONS}
        for record in applied:
            revision = known.get(int(record["version"]))
            if revision is None or record["name"] != revision.name or record["checksum"] != revision.checksum:
                raise RuntimeError("PostgreSQL migration history/checksum mismatch; refusing to continue.")
        current = versions[-1] if versions else 0
        if current > POSTGRES_MIGRATIONS[-1].version:
            raise RuntimeError("PostgreSQL schema is newer than this application.")

        for revision in POSTGRES_MIGRATIONS:
            if revision.version <= current:
                continue
            if revision.version != current + 1:
                raise RuntimeError("PostgreSQL migration definitions are not contiguous.")
            try:
                for statement in revision.statements:
                    db.execute(statement)
                db.execute("INSERT INTO schema_migrations(version,name,checksum,applied_at) VALUES(?,?,?,?)",
                    (revision.version,revision.name,revision.checksum,datetime.now(timezone.utc).isoformat()))
                db.commit()
                current = revision.version
                if revision.version != POSTGRES_MIGRATIONS[-1].version:
                    db.execute("BEGIN IMMEDIATE")
            except Exception:
                db.rollback()
                raise
        return current


def inspect_migration_state() -> dict[str, object]:
    """Read-only validation of an empty, current, or known upgradeable schema."""
    import re
    with postgres_connection() as db:
        tables = {str(row["table_name"]) for row in db.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE'").fetchall()}
        if not tables:
            return {"read_only": True, "current_version": 0, "target_version": POSTGRES_MIGRATIONS[-1].version,
                "schema_state": "empty_fresh", "pending": [revision.version for revision in POSTGRES_MIGRATIONS]}
        if "schema_migrations" not in tables:
            raise RuntimeError("PostgreSQL schema has tables but no verified migration ledger.")
        records = db.execute("SELECT version,name,checksum FROM schema_migrations ORDER BY version").fetchall()
        versions = [int(record["version"]) for record in records]
        if versions != list(range(1, len(versions) + 1)):
            raise RuntimeError("PostgreSQL migration history is not contiguous; refusing to migrate.")
        known = {revision.version: revision for revision in POSTGRES_MIGRATIONS}
        for record in records:
            revision = known.get(int(record["version"]))
            if revision is None or record["name"] != revision.name or record["checksum"] != revision.checksum:
                raise RuntimeError("PostgreSQL migration history/checksum mismatch; refusing to migrate.")
        expected = {"schema_migrations"}
        for revision in POSTGRES_MIGRATIONS:
            if revision.version > len(versions):
                break
            for statement in revision.statements:
                match = re.match(r"\s*CREATE\s+TABLE\s+([A-Za-z_][A-Za-z0-9_]*)", statement, re.IGNORECASE)
                if match:
                    expected.add(match.group(1))
        if tables != expected:
            raise RuntimeError("PostgreSQL public schema does not match its verified migration history.")
        current = len(versions)
        if current >= 2:
            columns = {str(row["column_name"]) for row in db.execute(
                "SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='conversations'").fetchall()}
            if not {"retention_class", "last_activity_at"}.issubset(columns):
                raise RuntimeError("PostgreSQL retention schema is incomplete.")
        return {"read_only": True, "current_version": current,
            "target_version": POSTGRES_MIGRATIONS[-1].version,
            "schema_state": "verified_current" if current == POSTGRES_MIGRATIONS[-1].version else "verified_upgradeable",
            "pending": [revision.version for revision in POSTGRES_MIGRATIONS if revision.version > current]}


def verify_ready() -> dict[str, object]:
    target_version = POSTGRES_MIGRATIONS[-1].version
    state = inspect_migration_state()
    if state["schema_state"] != "verified_current":
        raise RuntimeError("PostgreSQL schema is not at the current verified revision.")
    with postgres_connection() as db:
        result = db.execute("SELECT version,name,checksum FROM schema_migrations ORDER BY version").fetchall()
        versions = [int(record["version"]) for record in result]
        known = {revision.version: revision for revision in POSTGRES_MIGRATIONS}
        valid = versions == list(range(1, target_version + 1)) and len(result) == target_version
        valid = valid and all(record["name"] == known[int(record["version"])].name
            and record["checksum"] == known[int(record["version"])].checksum for record in result)
        if not valid:
            raise RuntimeError("PostgreSQL schema is missing, pending, or has a migration checksum mismatch.")
        missing = db.execute("""SELECT required.table_name FROM (VALUES
            ('accounts'),('conversations'),('messages'),('preferences'),('approved_memories'),
            ('user_sessions'),('external_identities'),('account_emails'),('auth_sessions'),
            ('email_action_tokens'),('oauth_transactions'),('email_auth_throttles'),
            ('security_rate_limits'),('security_operation_leases'),('anonymous_storage_usage'),
            ('anonymous_storage_global'),('anonymous_message_usage_map'),('legacy_data_quarantine'),
            ('cloud_budget_daily'),('cloud_budget_reservations'),('cloud_active_requests'),
            ('conversation_activity_leases'),('data_deletion_tombstones'),('account_deletion_requests')
        ) AS required(table_name) LEFT JOIN information_schema.tables t
          ON t.table_schema='public' AND t.table_name=required.table_name
          WHERE t.table_name IS NULL""").fetchall()
        if missing:
            raise RuntimeError("PostgreSQL schema is incomplete.")
        trigger_rows = db.execute("""SELECT tgname FROM pg_trigger g JOIN pg_class c ON c.oid=g.tgrelid
            JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND NOT g.tgisinternal
            AND tgname IN ('quarantine_conversation','quarantine_preference','quarantine_memory',
              'anonymous_conversation_insert','anonymous_conversation_delete','anonymous_conversation_owner_update',
              'anonymous_message_insert','anonymous_message_delete','anonymous_message_owner_update')""").fetchall()
        expected_triggers = {"quarantine_conversation","quarantine_preference","quarantine_memory",
            "anonymous_conversation_insert","anonymous_conversation_delete","anonymous_conversation_owner_update",
            "anonymous_message_insert","anonymous_message_delete","anonymous_message_owner_update"}
        if {row["tgname"] for row in trigger_rows} != expected_triggers:
            raise RuntimeError("PostgreSQL quota or quarantine triggers are incomplete.")
    return {"database_dialect":"postgresql","read_only":True,"current_version":target_version,
            "target_version":target_version,"pending":[],"integrity_check":"not_applicable",
            "foreign_key_violations":0}
